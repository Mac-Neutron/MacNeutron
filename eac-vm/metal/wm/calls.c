#define FIELDS(...)                                                                                                    \
    .nfields = sizeof((const struct mn_wm_field[]){__VA_ARGS__}) / sizeof(struct mn_wm_field),                       \
    .fields = (const struct mn_wm_field[]) { __VA_ARGS__ }
#define C(slot, nm, st, md, sp, ...)                                                                                   \
    [slot] = {.name = #nm, .params_size = sizeof(struct st), .mode = md, .special = sp, FIELDS(__VA_ARGS__)}
#define C0(slot, nm, st, md, sp) [slot] = {.name = #nm, .params_size = sizeof(struct st), .mode = md, .special = sp}
#define R(slot, nm, size, status)                                                                                      \
    [slot] = {.name = #nm, .params_size = size, .mode = MN_WM_REFUSED, .refuse_status = status}
